COMPILED = [(name, re.compile(rx, re.IGNORECASE), re.compile(exc, re.IGNORECASE) if exc else None) for name, rx, exc in RULES]


def violations(text: str):
    """Список нарушений канона в одной реплике Миры: [(правило, фрагмент)]."""
    found = []
    for name, rx, exc in COMPILED:
        for m in rx.finditer(text or ""):
            if exc is not None and exc.search(text):
                continue
            found.append((name, m.group(0)))
    return found
