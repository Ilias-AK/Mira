COMPILED = [(re.compile(p), answers) for p, answers in FRAMES]


def frame_answer(question_ty: str, used=(), salt="") -> str | None:
    q = question_ty
    for pattern, answers in COMPILED:
        if pattern.search(q):
            fresh = [a for a in answers if norm(a) not in used]
            if not fresh:
                continue
            digest = hashlib.sha256(f"{q}|{salt}".encode("utf-8")).digest()
            return fresh[digest[0] % len(fresh)]
    return None


def frame_key(question_ty: str):
    """Index of the first frame that fits the question (for 'я же уже говорила'), or None."""
    for index, (pattern, _answers) in enumerate(COMPILED):
        if pattern.search(question_ty):
            return index
    return None
